  int numero, {
  required String trait,
  required bool reversed,
  required String en,
  required String fr,
  required String de,
  required String es,
  required String pt,
  String? enGB,
}) =>
    QItem(
      id: 'ipip50_q${numero.toString().padLeft(2, '0')}',
      subscale: trait,
      reverseScored: reversed,
      text: QText(fr: fr, en: en, enGB: enGB ?? en, de: de, es: es, pt: pt),
    );

